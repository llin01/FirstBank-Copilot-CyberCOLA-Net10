            // Appended to every SQL connection string. Enabled unless the service's appsettings.json sets
            // GeneralConfig:sql-column-encryption-setting to "Disabled". The test database (NCARD) has no Always
            // Encrypted keys or columns (checked 2026-11-17); production must be checked by a DBA before disabling it
            // there, because encrypted columns would then come back as ciphertext and writes to them would fail.
            public static readonly string ColumnEncryptionSetting = ResolveColumnEncryptionSetting(ReadColumnEncryptionConfig());

            /// <summary>Maps the configured value to the connection string keyword; anything but "Disabled" keeps it enabled.</summary>
            public static string ResolveColumnEncryptionSetting(string? configured) =>
                string.Equals(configured?.Trim(), "Disabled", StringComparison.OrdinalIgnoreCase)
                    ? "Column Encryption Setting=disabled"
                    : "Column Encryption Setting=enabled";

            private static string? ReadColumnEncryptionConfig()
            {
                try
                {
                    return new Com.Cybersoft4u.CyberUtils.Utils.ConfigurationLoaderRoot().Get(ConfigSectionName.GeneralConfigSectionName, "sql-column-encryption-setting");
                }
                catch (Exception)
                {
                    // A configuration problem must never stop a service from connecting the way it always has.
                    return null;
                }
            }
